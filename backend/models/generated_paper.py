"""
SQLAlchemy Models for Generated Papers and Questions.

Represents AI-generated question papers and their constituent questions.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    Column,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import relationship

from backend.database import Base


class GeneratedPaper(Base):
    """
    Represents an AI-generated question paper.

    Attributes:
        id: Unique identifier.
        subject: Subject name.
        title: Paper title (e.g., "End-Term Examination 2024").
        generation_config: JSONB with constraints and template settings.
        selected_questions: Ordered list of selected/generated questions.
        validation_report: Results from the validation engine.
        pdf_path: Path to the generated PDF file.
        status: Current status of the generated paper.
        created_at: When the paper was generated.
    """

    __tablename__ = "generated_papers"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    subject = Column(String(255), nullable=False, index=True)
    title = Column(String(500), nullable=False)
    generation_config = Column(JSONB, nullable=False)
    selected_questions = Column(JSONB, nullable=True)
    validation_report = Column(JSONB, nullable=True)
    pdf_path = Column(String(1000), nullable=True)
    status = Column(String(50), nullable=False, default="draft")
    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # Relationships
    generated_questions = relationship(
        "GeneratedQuestion",
        back_populates="generated_paper",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<GeneratedPaper(id={self.id}, subject='{self.subject}', status='{self.status}')>"


class GeneratedQuestion(Base):
    """
    Represents a single question within a generated paper.

    Can be either newly generated by AI or selected from the
    existing question pool.

    Attributes:
        id: Unique identifier.
        generated_paper_id: Foreign key to the parent GeneratedPaper.
        question_text: The question text.
        marks: Marks allocated.
        section: Section of the paper this question belongs to.
        unit: Syllabus unit this question covers.
        blooms_level: Bloom's taxonomy level.
        source: Whether this question was "generated" or from "pool".
        source_question_id: If from pool, the original question's ID.
    """

    __tablename__ = "generated_questions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    generated_paper_id = Column(
        UUID(as_uuid=True),
        ForeignKey("generated_papers.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    question_text = Column(Text, nullable=False)
    marks = Column(Integer, nullable=False)
    section = Column(String(50), nullable=True)
    unit = Column(String(100), nullable=True)
    blooms_level = Column(String(50), nullable=True)
    source = Column(String(20), nullable=False, default="generated")
    source_question_id = Column(UUID(as_uuid=True), nullable=True)

    # Relationships
    generated_paper = relationship("GeneratedPaper", back_populates="generated_questions")

    def __repr__(self) -> str:
        return (
            f"<GeneratedQuestion(id={self.id}, marks={self.marks}, "
            f"source='{self.source}')>"
        )
